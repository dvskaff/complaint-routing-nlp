"""README results block and MODEL_CARD.md, rewritten after every real run."""

from __future__ import annotations

import re

import pandas as pd

from .report import short


def _p(v) -> str:
    return "–" if v is None or pd.isna(v) else f"{v:.1%}"


def update(cfg, run: dict, scores: dict, topics: dict, dups: dict) -> None:
    from .pipeline import ENS_NAME, FT_NAME

    ft, tf, emb = (
        scores[FT_NAME],
        scores["TF-IDF + logistic regression"],
        scores["Sentence embeddings + logistic regression"],
    )
    maj = scores["Majority class"]
    r = ft["routing"]
    w = run["window"]
    lines = [
        f"_CFPB narrative archive · trained on {w['train'][0]} to {w['train'][-1]} ({run['train']:,} complaints), "
        f"tested on {w['test'][0]} to {w['test'][-1]} ({run['test']:,} complaints, real product mix) · "
        f"{len(run['labels'])} products · last run {run['built_at']}_",
        "",
        "| Model (test months) | Accuracy | Macro-F1 | Auto-routed at "
        f"{cfg.target_accuracy:.0%} target | Accuracy when auto-routed |",
        "|---|---|---|---|---|",
    ]
    for name, s in [("Majority class", maj), ("TF-IDF + logistic regression", tf),
                    ("Sentence embeddings + logistic regression", emb), (FT_NAME, ft),
                    (ENS_NAME, scores[ENS_NAME])]:  # fmt: skip
        bold = "**" if name == FT_NAME else ""
        lines.append(f"| {bold}{name}{bold} | {_p(s['accuracy'])} | {s['macro_f1']:.3f} | "
                     f"{_p(s['routing']['auto_share'])} | {_p(s['routing']['auto_accuracy'])} |")  # fmt: skip
    lines += [
        "",
        f"**Routing policy:** auto-route when calibrated confidence ≥ {r['threshold']:.1%} → {_p(r['auto_share'])} of "
        f"complaints go straight to a team ({_p(r['auto_accuracy'])} correct); the rest go to a person, with the right "
        f"team in the top two suggestions {_p(r['review_top2'])} of the time.",
        "",
        f"**Browser model:** {run['onnx']['size_mb']:.0f} MB 8-bit ONNX (calibration built in), "
        f"same routing decision as the full model on {run['onnx']['decision_agreement']:.1%} of complaints · "
        f"[try it]({cfg.repo_url.replace('github.com/dvskaff', 'dvskaff.github.io')}/#demo)",
    ]
    if topics["emerging"]:
        top = topics["emerging"][:3]
        items = "; ".join(f"{t['label']} ({_p(t['base_share'])} → {_p(t['recent_share'])}, {short(t['top_product'])})"
                          for t in top)  # fmt: skip
        lines += [
            "",
            f"**Emerging issues (BERTopic, last {len(topics['recent_months'])} months vs. before):** {items}",
        ]
    lines += ["", f"_Template letters: {_p(dups['share_in_train'])} of test narratives also appear word for word in "
                  f"training; on the rest, macro-F1 is {dups.get('unseen', {}).get('macro_f1', float('nan')):.3f}._"]  # fmt: skip
    block = "\n".join(lines)
    text = cfg.readme.read_text()
    text = re.sub(r"(<!-- RESULTS:START -->).*?(<!-- RESULTS:END -->)", lambda m: f"{m.group(1)}\n{block}\n{m.group(2)}",
                  text, flags=re.S)  # fmt: skip
    cfg.readme.write_text(text)


def model_card(cfg, run: dict, scores: dict, per_class: pd.DataFrame, dups: dict) -> None:
    from .pipeline import FT_NAME

    ft = scores[FT_NAME]
    r = ft["routing"]
    w = run["window"]
    rows = "\n".join(f"| {short(x.product)} | {x.precision:.2f} | {x.recall:.2f} | {x.f1:.2f} | {x.support:,} |"
                     for x in per_class.sort_values("support", ascending=False).itertuples())  # fmt: skip
    text = f"""# Model card: complaint router

_Generated by the pipeline on {run["built_at"]}. Numbers are on held-out test months._

## What it does
Reads the free-text narrative of a consumer financial complaint and predicts which of {len(run["labels"])} product
areas it belongs to (the CFPB's product categories), with a calibrated confidence. A routing policy sends confident
predictions straight to the product team and the rest to human review.

## Model
- Base: `{run["base_model"]}` (6-layer MiniLM, 22M parameters), fine-tuned end to end with a classification head.
- Input: the first {cfg.max_tokens} tokens of the narrative (after removing the CFPB's XXXX redaction marks).
- Training: {run["finetune"]["train_size"]:,} complaints from {w["train"][0]} to {w["train"][-1]}, at most
  {cfg.train_cap_per_product:,} per product; {cfg.epochs} epochs, AdamW, learning rate {cfg.learning_rate}, batch
  {cfg.batch_size}; best epoch by validation macro-F1 (epoch {run["finetune"]["best_epoch"]}).
- Calibration: prior correction for the real product mix (strength {ft["prior_strength"]:.2f}, chosen on validation
  so small products still get predicted) + temperature scaling (T = {ft["temperature"]:.2f}), fitted on {w["val"]}.
- Deployment format: ONNX, 8-bit dynamic quantization, {run["onnx"]["size_mb"]:.0f} MB, calibration inside the graph;
  on {run["onnx"]["n"]:,} validation complaints it makes the same routing decision as PyTorch {run["onnx"]["decision_agreement"]:.1%}
  of the time and picks the same top team {run["onnx"]["top1_agreement"]:.1%} of the time.

## Results ({w["test"][0]} to {w["test"][-1]}, {run["test"]:,} complaints, real mix)
- Accuracy {ft["accuracy"]:.1%} · macro-F1 {ft["macro_f1"]:.3f} · weighted F1 {ft["weighted_f1"]:.3f} · top-2
  accuracy {ft["top2_accuracy"]:.1%}
- Calibration error (ECE) {ft["ece_uncalibrated"]:.3f} before calibration, {ft["ece"]:.3f} after
- Routing policy (confidence ≥ {r["threshold"]:.1%}): {r["auto_share"]:.1%} auto-routed at {r["auto_accuracy"]:.1%}
  accuracy
- Template letters: {dups["share_in_train"]:.1%} of test narratives appear word for word in training; macro-F1 on the
  others is {dups.get("unseen", {}).get("macro_f1", float("nan")):.3f}

| Product | Precision | Recall | F1 | Test complaints |
|---|---|---|---|---|
{rows}

## Intended use and limits
- Intended for triage support: suggesting a team and flagging uncertain complaints for a person. Not for deciding
  outcomes for consumers.
- Labels are the product the consumer selected when filing, so some disagreement is labeling noise, not model error.
- English narratives only; long narratives are truncated; products with fewer than
  {cfg.min_train_per_product} training complaints are not predicted.
- The CFPB stopped publishing narratives in August 2026, so the data ends there. A live deployment would need fresh
  labeled complaints and drift monitoring.
- Narratives are public, consumer-consented and redacted by the CFPB; the model is not trained to extract personal data.
"""
    cfg.model_card.write_text(text)
